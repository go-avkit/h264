type avail8x8Case struct {
	name  string
	avail Availability
}

func TestIntra8x8MatchesReferenceFormulas(t *testing.T) {
	cases := []avail8x8Case{
		{"all", AvailLeft | AvailTop | AvailTopLeft | AvailTopRight},
		{"noTopRight", AvailLeft | AvailTop | AvailTopLeft},
		{"noTopLeft", AvailLeft | AvailTop | AvailTopRight},
		{"noTopLeftNoTopRight", AvailLeft | AvailTop},
		{"leftOnly", AvailLeft},
		{"topOnly", AvailTop | AvailTopRight},
		{"none", 0},
	}
	rng := rand.New(rand.NewSource(20260901))
	for _, c := range cases {
		for mode := 0; mode < 9; mode++ {
			if !Intra8x8ModeAvailable(mode, c.avail) {
				continue
			}
			for iter := 0; iter < 40; iter++ {
				p := newPlane8x8(rng)
				ref, refL, refLT := oracleRefs8x8(p, c.avail.Has(AvailTopLeft), c.avail.Has(AvailTopRight))
				var want [64]int
				oracleIntra8x8(&want, ref, refL, refLT, mode,
					c.avail.Has(AvailTop), c.avail.Has(AvailLeft))
				Intra8x8(p.buf, p.stride, p.off, mode, c.avail)
				for y := 0; y < 8; y++ {
					for x := 0; x < 8; x++ {
						got := p.at(x, y)
						if got != int(clip1(want[y*8+x])) {
							t.Fatalf("%s mode %d iter %d at (%d,%d): got %d want %d",
								c.name, mode, iter, x, y, got, want[y*8+x])
						}
					}
				}
			}
		}
	}
}

func TestIntra8x8CoversEveryMode(t *testing.T) {
	avail := AvailLeft | AvailTop | AvailTopLeft | AvailTopRight
	seen := make(map[[64]byte]int)
	source := newPlane8x8(rand.New(rand.NewSource(7)))
	for mode := 0; mode < 9; mode++ {
		p := plane8x8{buf: append([]byte(nil), source.buf...), stride: source.stride, off: source.off}
		Intra8x8(p.buf, p.stride, p.off, mode, avail)
		var got [64]byte
		for y := 0; y < 8; y++ {
			for x := 0; x < 8; x++ {
				got[y*8+x] = byte(p.at(x, y))
			}
		}
		if prev, ok := seen[got]; ok {
			t.Fatalf("mode %d produced the same block as mode %d", mode, prev)
		}
		seen[got] = mode
	}
}
