type plane8x8 struct {
	buf    []byte
	stride int
	off    int
}

func newPlane8x8(rng *rand.Rand) plane8x8 {
	p := plane8x8{buf: make([]byte, 32*24), stride: 32}
	p.off = 8*p.stride + 8
	for i := range p.buf {
		p.buf[i] = byte(rng.Intn(256))
	}
	return p
}

func (p plane8x8) at(x, y int) int { return int(p.buf[p.off+y*p.stride+x]) }

func oracleRefs8x8(p plane8x8, hasTopLeft, hasTopRight bool) (t [16]int, l [8]int, lt int) {
	first := p.at(-1, 0)
	if hasTopLeft {
		first = p.at(-1, -1)
	}
	l[0] = (first + 2*p.at(-1, 0) + p.at(-1, 1) + 2) >> 2
	for y := 1; y <= 6; y++ {
		l[y] = (p.at(-1, y-1) + 2*p.at(-1, y) + p.at(-1, y+1) + 2) >> 2
	}
	l[7] = (p.at(-1, 6) + 3*p.at(-1, 7) + 2) >> 2

	first = p.at(0, -1)
	if hasTopLeft {
		first = p.at(-1, -1)
	}
	t[0] = (first + 2*p.at(0, -1) + p.at(1, -1) + 2) >> 2
	for x := 1; x <= 6; x++ {
		t[x] = (p.at(x-1, -1) + 2*p.at(x, -1) + p.at(x+1, -1) + 2) >> 2
	}
	last := p.at(7, -1)
	if hasTopRight {
		last = p.at(8, -1)
	}
	t[7] = (last + 2*p.at(7, -1) + p.at(6, -1) + 2) >> 2
	if hasTopRight {
		for x := 8; x <= 14; x++ {
			t[x] = (p.at(x-1, -1) + 2*p.at(x, -1) + p.at(x+1, -1) + 2) >> 2
		}
		t[15] = (p.at(14, -1) + 3*p.at(15, -1) + 2) >> 2
	} else {
		for x := 8; x < 16; x++ {
			t[x] = p.at(7, -1)
		}
	}
	lt = (p.at(-1, 0) + 2*p.at(-1, -1) + p.at(0, -1) + 2) >> 2
	return
}

